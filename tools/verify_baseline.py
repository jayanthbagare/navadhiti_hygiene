#!/usr/bin/env python3
"""navadhiti hygiene — repository baseline verifier.

Answers one question: does this repository meet the baseline it enforces on
other repositories? One command, one verdict, every criterion — so that
"is this repository healthy?" has exactly one answer source.

    python tools/verify_baseline.py

Governed by specs/001-fix-own-repo-hygiene/contracts/verify-baseline-cli.md.
The shape of the internal entities is fixed by that feature's data-model.md.

Stdlib only, on purpose. One criterion is "the test suite is green", so a
verifier that imported a third-party package could be disabled by the very
broken `pip install` it exists to catch. It reads git-tracked state, writes
nothing, and works from any working directory.

Exit codes are the contract's most important guarantee:

    0  every criterion passed
    1  the repository does not meet its baseline
    2  the verifier could not run — NOT a statement about the repository

Nothing here ever prints a denied identifier, a credential value, or a token
fragment. Findings reference a path, a line number, a count, or a pattern
name, so a report can be pasted into a ticket without re-exporting the secret
it found.
"""

