# Shared helpers
# --------------------------------------------------------------------------

def _offending_env_files(tracked: Iterable[str]) -> list[str]:
    """Tracked paths that live inside an environment directory."""
    return [
        path for path in tracked
        if any(part in ENV_DIR_NAMES for part in Path(path).parts[:-1])
        or Path(path).name in ENV_DIR_NAMES
    ]


def _yaml_load(text: str) -> object:
    """Parse YAML with PyYAML when installed; otherwise signal "unavailable".

    The verifier is stdlib-only so a broken dependency install cannot disable
    the check that catches it. When PyYAML is absent, callers fall back to a
    targeted field reader that answers the same question from the text.
    """
    try:
        import yaml  # noqa: PLC0415 — optional by design
    except ImportError:
        return _YAML_UNAVAILABLE
    try:
        return yaml.safe_load(text)
    except Exception as exc:  # yaml.YAMLError and friends
        return exc


class _YamlUnavailable:
    def __repr__(self) -> str:  # pragma: no cover — debugging aid
        return "<PyYAML unavailable>"


_YAML_UNAVAILABLE = _YamlUnavailable()


def _scalar(text: str) -> str:
    return text.split("#", 1)[0].strip().strip("'\"")


