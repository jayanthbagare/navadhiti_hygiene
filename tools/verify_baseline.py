EXIT_FAIL = 1
EXIT_CANNOT_RUN = 2

CRITERION_ID_RE = re.compile(r"^[a-z0-9-]+$")


class VerifierCannotStart(RuntimeError):
    """The verifier itself could not run. Exit 2, never a repository verdict."""


# --------------------------------------------------------------------------
# Entities (data-model.md)
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class Criterion:
    """One baseline assertion the verifier evaluates."""

    id: str
    label: str
    requirements: tuple[str, ...]
    determination: str
    cannot_determine_action: str
    check: Callable[["Repository"], "CriterionResult"]

    def __post_init__(self) -> None:
        if not CRITERION_ID_RE.match(self.id):
            raise VerifierCannotStart(
                f"criterion id {self.id!r} must be kebab-case ([a-z0-9-]+)")
        if not self.requirements:
            raise VerifierCannotStart(
                f"criterion {self.id!r} traces to no requirement; that is scope creep")
        if self.determination != "observed":
            # Rejected at startup, not at evaluation time: a criterion whose
            # determination is undecided cannot honestly produce a verdict.
            raise VerifierCannotStart(
                f"criterion {self.id!r} has determination {self.determination!r}; "
                "only 'observed' is permitted in this milestone")
        if self.cannot_determine_action not in ("report_unverifiable", "fail"):
            raise VerifierCannotStart(
                f"criterion {self.id!r} has an unknown cannot_determine_action "
                f"{self.cannot_determine_action!r}")


@dataclass(frozen=True)
class CriterionResult:
    """The outcome of evaluating one Criterion against the working tree."""

    criterion_id: str
    status: str
    detail: str
    evidence: tuple[str, ...] = ()
    observed: dict = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.status not in (STATUS_PASS, STATUS_FAIL, STATUS_UNVERIFIABLE):
            raise ValueError(
                f"criterion {self.criterion_id!r} produced status {self.status!r}")
        if self.status == STATUS_FAIL and not self.detail:
            raise ValueError(
                f"criterion {self.criterion_id!r} failed without saying why")
        if self.status == STATUS_UNVERIFIABLE and not self.detail:
            raise ValueError(
                f"criterion {self.criterion_id!r} could not be evaluated without "
                "naming what was missing")


@dataclass(frozen=True)
class BaselineReport:
    """The complete result of one verifier run."""

    criteria: tuple[CriterionResult, ...]
    verdict: str
    commit: Optional[str]
    generated_at: str
    blocking: bool = False

    @property
    def failed(self) -> int:
        return sum(1 for r in self.criteria if r.status != STATUS_PASS)


# --------------------------------------------------------------------------
# Repository — read-only view of git-tracked state
# --------------------------------------------------------------------------

class Repository:
    """A read-only handle on the checkout.

    Holds nothing that outlives one run and writes nothing at all, which is
    what lets the verifier be run on a colleague's checkout without asking and
    what makes two runs against one commit produce identical output.
    """

    def __init__(self, root: Path) -> None:
        self.root = root
        self._tracked: Optional[tuple[str, ...]] = None
        self._commit: Optional[str] = None
        self._commit_resolved = False

    # -- git -------------------------------------------------------------

    def _git(self, *args: str) -> str:
        try:
            proc = subprocess.run(
                ["git", "-C", str(self.root), *args],
                capture_output=True, text=True, timeout=60,
            )
        except FileNotFoundError as exc:
            raise VerifierCannotStart("git is not available on PATH") from exc
        except subprocess.TimeoutExpired as exc:
            raise VerifierCannotStart(f"git {' '.join(args)} timed out") from exc
        if proc.returncode != 0:
            raise VerifierCannotStart(
                f"git {' '.join(args)} failed: {proc.stderr.strip()}")
        return proc.stdout

    def tracked_files(self) -> tuple[str, ...]:
        """Repository-relative POSIX paths of every tracked file, sorted."""
        if self._tracked is None:
            out = self._git("ls-files", "-z")
            self._tracked = tuple(sorted(p for p in out.split("\0") if p))
        return self._tracked

    def commit_sha(self) -> Optional[str]:
        """Current commit SHA, or None outside a repository.

        Prints as absent rather than as a placeholder: a fabricated SHA would
        make two different states look identical in the output.
        """
        if not self._commit_resolved:
            try:
                self._commit = self._git("rev-parse", "HEAD").strip() or None
            except VerifierCannotStart:
                self._commit = None
            self._commit_resolved = True
        return self._commit

    # -- filesystem ------------------------------------------------------

    def path(self, relative: str) -> Path:
        return self.root / relative

    def exists(self, relative: str) -> bool:
        return self.path(relative).is_file()

    def read_text(self, relative: str) -> str:
        return self.path(relative).read_text(encoding="utf-8", errors="replace")

    def tracked_text_files(self) -> Iterator[tuple[str, list[str]]]:
        """Yield (path, lines) for every tracked text file worth scanning."""
        for relative in self.tracked_files():
            if any(part in SCAN_SKIP_PARTS for part in Path(relative).parts):
                continue
            lines = self._read_lines(relative)
            if lines is not None:
                yield relative, lines

    def _read_lines(self, relative: str) -> Optional[list[str]]:
        target = self.path(relative)
        try:
            raw = target.read_bytes()
        except (OSError, ValueError):
            return None
        if b"\0" in raw[:8192]:
            return None  # binary
        return raw.decode("utf-8", errors="replace").splitlines()


